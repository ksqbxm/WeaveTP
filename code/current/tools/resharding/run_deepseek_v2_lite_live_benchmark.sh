#!/usr/bin/env bash
set -euo pipefail

CHECKPOINT=${CHECKPOINT:-/home/ubuntu/models/DeepSeek-V2-Lite-megatron-v2}
PROFILE=${PROFILE:-profiles/moe_tp_8gpu_idle_p2p_v21.json}
OUT_DIR=${OUT_DIR:-outputs/deepseek_v2_lite_wave_tuned_$(date +%Y%m%d_%H%M%S)}

if [[ "${ADAPTIVE_HYBRID:-0}" == "1" ]]; then
    # On DeepSeek-V2-Lite, source rerouting already balances the large plan.
    # Repacking rerouted shards adds allocator/copy overhead without reducing waves.
    DEFAULT_PACK_TARGET_BYTES=0
    DEFAULT_PACK_MAX_ITEM_BYTES=0
    # Two repeated alternating-switch runs found 2,048 tasks/wave to be the
    # fastest setting that also avoided a foreground P95 TPOT regression.
    DEFAULT_MAX_WAVES=128
    DEFAULT_MAX_WAVE_TASKS=2048
else
    DEFAULT_PACK_TARGET_BYTES=4194304
    DEFAULT_PACK_MAX_ITEM_BYTES=1048576
    DEFAULT_MAX_WAVES=3
    DEFAULT_MAX_WAVE_TASKS=0
fi

if [[ ! -d "$CHECKPOINT" ]]; then
    echo "Converted DeepSeek-V2-Lite checkpoint not found: $CHECKPOINT" >&2
    exit 2
fi

MODEL_PRESET=deepseek-v2-lite \
METHOD_VARIANT=${METHOD_VARIANT:-moetp++} \
LOAD_CHECKPOINT="$CHECKPOINT" \
CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7} \
PROFILE="$PROFILE" \
NPROC_PER_NODE=8 \
EXPERT_PARALLEL_SIZE=2 \
ROUTER_MODE=${ROUTER_MODE:-fixed-hot} \
ACTIVE_EXPERTS=${ACTIVE_EXPERTS:-0,1,2,3,4,5} \
PROMPT_TOKENS=${PROMPT_TOKENS:-8} \
SEQ_LENGTH=${SEQ_LENGTH:-128} \
MAX_POSITION_EMBEDDINGS=${MAX_POSITION_EMBEDDINGS:-128} \
SWITCHES=${SWITCHES:-1} \
REPEAT_FORWARD=${REPEAT_FORWARD:-0} \
MAX_WAVES=${MAX_WAVES:-$DEFAULT_MAX_WAVES} \
MAX_WAVE_TASKS=${MAX_WAVE_TASKS:-$DEFAULT_MAX_WAVE_TASKS} \
MAX_OVERLAP_STEPS=${MAX_OVERLAP_STEPS:-1} \
SCHEDULER_MODE=${SCHEDULER_MODE:-residual} \
HYBRID_FAST_PATH=${HYBRID_FAST_PATH:-0} \
ALLOW_AWARE_SHRINK=${ALLOW_AWARE_SHRINK:-0} \
HYBRID_MIN_PREDICTED_GAIN_PCT=${HYBRID_MIN_PREDICTED_GAIN_PCT:-10.0} \
HYBRID_MAX_REMOTE_CV=${HYBRID_MAX_REMOTE_CV:-0.22} \
HYBRID_MAX_FOREGROUND_PRESSURE=${HYBRID_MAX_FOREGROUND_PRESSURE:-0.20} \
ADAPTIVE_HYBRID=${ADAPTIVE_HYBRID:-0} \
ADAPTIVE_MIN_PREDICTED_E2E_GAIN_PCT=${ADAPTIVE_MIN_PREDICTED_E2E_GAIN_PCT:-5.0} \
ADAPTIVE_RESIDUAL_MAX_WAVES=${ADAPTIVE_RESIDUAL_MAX_WAVES:-8} \
P2P_ORDER=${P2P_ORDER:-peer-size-desc} \
PACK_TARGET_BYTES=${PACK_TARGET_BYTES:-$DEFAULT_PACK_TARGET_BYTES} \
PACK_MAX_ITEM_BYTES=${PACK_MAX_ITEM_BYTES:-$DEFAULT_PACK_MAX_ITEM_BYTES} \
LOGIT_VALIDATION_MODE=${LOGIT_VALIDATION_MODE:-bf16-relative} \
LOGIT_MAX_NRMSE=${LOGIT_MAX_NRMSE:-0.4} \
LOGIT_MIN_COSINE=${LOGIT_MIN_COSINE:-0.93} \
LOGIT_MIN_TOP1_AGREEMENT=${LOGIT_MIN_TOP1_AGREEMENT:-0.0} \
OUT_DIR="$OUT_DIR" \
bash tools/resharding/run_live_moe_tp_benchmark.sh --out-dir "$OUT_DIR"
